/* =========================================================
   Motor de idioma
   ========================================================= */
function applyLanguage(lang){
  document.documentElement.setAttribute('lang', lang === 'es' ? 'es' : 'en');
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.es;

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const key = el.getAttribute('data-i18n-html');
    if(dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll('.lang-toggle button').forEach(btn=>{
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  localStorage.setItem('portfolio-lang', lang);
}

function initLangToggle(){
  const saved = localStorage.getItem('portfolio-lang') || 'es';
  applyLanguage(saved);
  document.querySelectorAll('.lang-toggle button').forEach(btn=>{
    btn.addEventListener('click', ()=> applyLanguage(btn.getAttribute('data-lang')));
  });
}

/* =========================================================
   Scroll reveal
   ========================================================= */
function initReveal(){
  const revealEls = document.querySelectorAll('.reveal');
  const observer = new IntersectionObserver((entries)=>{
    entries.forEach(e=>{ if(e.isIntersecting){ e.target.classList.add('visible'); observer.unobserve(e.target);} });
  }, {threshold:.15});
  revealEls.forEach(el=>observer.observe(el));
}

/* =========================================================
   Nav activa según la página actual
   ========================================================= */
function initActiveNav(){
  const path = window.location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.nav-links a').forEach(a=>{
    const href = a.getAttribute('href');
    a.classList.toggle('active', href === path);
  });
}

/* =========================================================
   Menú móvil
   ========================================================= */
function initMobileMenu(){
  const menuBtn = document.getElementById('menuBtn');
  const navLinksEl = document.querySelector('.nav-links');
  if(!menuBtn || !navLinksEl) return;
  menuBtn.addEventListener('click', ()=>{
    const isOpen = navLinksEl.style.display === 'flex';
    navLinksEl.style.cssText = isOpen ? '' : 'display:flex; flex-direction:column; gap:16px; position:absolute; top:64px; right:24px; background:#15151b; padding:20px 24px; border-radius:12px; border:1px solid #26262f;';
  });
}

document.addEventListener('DOMContentLoaded', ()=>{
  initLangToggle();
  initReveal();
  initActiveNav();
  initMobileMenu();
});
